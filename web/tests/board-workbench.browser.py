import argparse
from datetime import datetime, timezone
from pathlib import Path
from playwright.sync_api import sync_playwright, expect

parser = argparse.ArgumentParser()
parser.add_argument('--url', required=True)
parser.add_argument('--output', default='/private/tmp/astock-board-workbench-qa')
args = parser.parse_args()
output = Path(args.output)
output.mkdir(exist_ok=True)
expect.set_options(timeout=30000)

with sync_playwright() as p:
    browser = p.chromium.launch(headless=True)
    try:
        page = browser.new_page(viewport={'width': 1440, 'height': 1050})
        page.clock.set_fixed_time(datetime(2026, 10, 16, 7, 40, tzinfo=timezone.utc))
        errors = []
        page.on('pageerror', lambda error: errors.append(str(error)))
        page.goto(args.url + '/?view=boards', wait_until='networkidle')
        panel = page.get_by_role('region', name='板块资金工作台')
        expect(panel).to_be_visible()
        expect(panel).to_have_attribute('aria-busy', 'false')
        expect(panel.locator('.bw-bubbles circle')).to_have_count(5)
        page.screenshot(path=str(output / 'initial.png'), full_page=True)
        panel.get_by_role('img', name='板块涨跌与资金四象限').get_by_role('button', name='银行 ', exact=False).click()
        expect(panel.locator('.bw-selection')).to_contain_text('银行')
        panel.get_by_role('region', name='关联候选', exact=True).get_by_role('button', name='浦发银行', exact=False).click()
        stock = panel.get_by_role('region', name='个股联动', exact=True)
        expect(stock).to_contain_text('12.30')
        stock.get_by_role('button', name='打开个股行情', exact=True).click()
        expect(panel).to_have_count(0)
        page.get_by_role('button', name='板块行情', exact=True).click()
        expect(panel.locator('.bw-selection')).to_contain_text('银行')
        expect(panel.get_by_role('img', name='板块每日主力净流入', exact=True)).to_be_visible()
        expect(panel.get_by_role('region', name='个股联动', exact=True)).to_contain_text('同板块成份股')
        panel.get_by_role('region', name='关联候选', exact=True).get_by_role('button', name='浦发银行', exact=False).click()
        expect(stock).to_contain_text('12.30')
        panel.get_by_role('button', name='资金榜单', exact=True).click()
        expect(panel.locator('.bw-table tbody tr')).to_have_count(5)
        panel.get_by_role('button', name='资金气泡', exact=True).click()
        page.clock.set_fixed_time(datetime(2026, 10, 16, 6, 59, tzinfo=timezone.utc))
        with page.expect_response(lambda response: '/api/board-daily-flows?' in response.url):
            panel.get_by_role('button', name='刷新板块', exact=True).click()
        expect(panel).to_have_attribute('aria-busy', 'false')
        page.clock.set_fixed_time(datetime(2026, 10, 16, 7, 0, tzinfo=timezone.utc))
        with page.expect_response(lambda response: '/api/board-daily-flows?' in response.url):
            panel.get_by_role('button', name='刷新板块', exact=True).click()
        expect(panel).to_have_attribute('aria-busy', 'false')
        page.clock.set_fixed_time(datetime(2026, 10, 16, 7, 40, tzinfo=timezone.utc))
        page.route('**/api/boards?sort=flow', lambda route: route.fulfill(status=502, content_type='application/json', body='{"warning":"HTTP 403 Forbidden"}'))
        panel.get_by_role('button', name='刷新板块', exact=True).click()
        expect(panel.locator('.bw-heading')).to_contain_text('保留快照')
        expect(panel.locator('.bw-bubbles circle')).to_have_count(5)
        page.unroute('**/api/boards?sort=flow')
        slider = panel.get_by_label('盘中回放时间', exact=True)
        slider.focus()
        slider.press('Home')
        expect(panel.locator('.bw-heading')).to_contain_text('历史回放')
        expect(stock).to_contain_text('11.5')
        expect(stock).not_to_contain_text('12.30')
        panel.get_by_role('button', name='播放回放', exact=True).click()
        expect(panel.get_by_role('button', name='暂停回放', exact=True)).to_be_visible()
        page.wait_for_timeout(1100)
        panel.get_by_role('button', name='暂停回放', exact=True).click()
        assert int(slider.input_value()) > 0
        panel.get_by_role('button', name='实时', exact=True).click()
        expect(panel.locator('.bw-heading')).to_contain_text('实时快照')
        panel.get_by_label('工作区预设').select_option('risk')
        expect(panel.locator('.bw-table')).to_be_visible()
        panel.get_by_role('button', name='调整布局', exact=True).click()
        panel.get_by_label('预设名称', exact=True).fill('我的盯盘')
        panel.get_by_role('button', name='保存预设', exact=True).click()
        preset = panel.get_by_label('工作区预设').input_value()
        page.reload(wait_until='networkidle')
        expect(panel.get_by_label('工作区预设')).to_have_value(preset)
        panel.get_by_label('工作区预设').select_option('intraday')
        for width in [1440, 900, 390, 320]:
            page.set_viewport_size({'width': width, 'height': 1050 if width > 600 else 844})
            assert page.evaluate('document.documentElement.scrollWidth <= innerWidth'), width
            page.screenshot(path=str(output / f'boards-{width}.png'), full_page=True)
        page.set_viewport_size({'width': 1440, 'height': 1050})
        page.goto(args.url + '/?view=monitor&monitor=native&event=fixture-event', wait_until='networkidle')
        panel = page.get_by_role('region', name='Mac 通知与跟踪')
        expect(panel).to_contain_text('浦发银行')
        panel.get_by_role('button', name='加入重点跟踪', exact=True).click()
        expect(panel.locator('.nn-follows').first).to_contain_text('sh600000')
        panel.get_by_role('button', name='当天静音', exact=True).click()
        expect(panel.get_by_role('button', name='恢复提醒', exact=True)).to_be_visible()
        panel.get_by_label('处理备注 fixture-event', exact=True).fill('次日复核资金')
        panel.get_by_role('button', name='保存备注', exact=True).click()
        panel.get_by_role('button', name='标为已处理', exact=True).click()
        expect(panel).to_contain_text('已处理')
        page.reload(wait_until='networkidle')
        expect(panel.get_by_label('处理备注 fixture-event', exact=True)).to_have_value('次日复核资金')
        for width in [1440, 390, 320]:
            page.set_viewport_size({'width': width, 'height': 900})
            assert page.evaluate('document.documentElement.scrollWidth <= innerWidth'), width
            page.screenshot(path=str(output / f'notifications-{width}.png'), full_page=True)
        assert not errors, errors
        print({'bubbles': True, 'replay': True, 'preset_restore': True, 'linked_stock': True, 'notification_actions': True, 'mobile': True})
    finally:
        browser.close()
